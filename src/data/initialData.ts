// Helper to make sample students for a class
function generateStudentsForClass(classId: string, className: string, count: number) {
  const students = [];
  const lastNames = ['Nguyễn', 'Trần', 'Lê', 'Phạm', 'Huỳnh', 'Võ', 'Phan', 'Trương', 'Bùi', 'Đặng', 'Ka Sô', 'Mô Lô', 'So'];
  const middleNamesM = ['Văn', 'Quốc', 'Đức', 'Hữu', 'Công', 'Minh', 'Thanh'];
  const middleNamesF = ['Thị', 'Ngọc', 'Thanh', 'Như', 'Kim', 'Thùy', 'Hồng'];
  const firstNamesM = ['Bảo', 'Dũng', 'Huy', 'Khánh', 'Long', 'Nam', 'Phúc', 'Tùng', 'Tuấn', 'Việt', 'Hưng', 'Lập'];
  const firstNamesF = ['Anh', 'Chi', 'Dung', 'Hà', 'Linh', 'Mai', 'Nga', 'Phương', 'Quỳnh', 'Thảo', 'Trang', 'Yến', 'Phương'];

  for (let i = 1; i <= count; i++) {
    const isMale = i % 2 === 1;
    const l = lastNames[(i * 3 + classId.length) % lastNames.length];
    const m = isMale ? middleNamesM[(i * 2) % middleNamesM.length] : middleNamesF[(i * 2) % middleNamesF.length];
    const f = isMale ? firstNamesM[(i * 5) % firstNamesM.length] : firstNamesF[(i * 5) % firstNamesF.length];
    const fullName = `${l} ${m} ${f}`;
    const isEthnic = l.startsWith('Ka Sô') || l.startsWith('Mô Lô') || l.startsWith('So');

    students.push({
      id: `${classId}_HS${i.toString().padStart(2, '0')}`,
      orderNumber: i,
      fullName,
      gender: isMale ? ('Nam' as const) : ('Nữ' as const),
      dob: `201${14 - Math.min(9, Math.max(1, parseInt(classId.replace(/\D/g, '') || '6')) + 5)}-0${(i % 9) + 1}-${((i * 3) % 27) + 1}`,
      ethnicity: isEthnic ? 'Chăm H’roi' : 'Kinh',
      address: 'Xã Đồng Xuân, Phú Yên',
      parentName: `${l} Văn ${isMale ? 'Tuấn' : 'Tùng'}`,
      parentPhone: '098' + Math.floor(1000000 + Math.random() * 9000000),
      status: 'Đang học' as const,
      policyBeneficiary: isEthnic || i % 7 === 0 ? ('Hộ nghèo' as const) : i % 5 === 0 ? ('Hộ cận nghèo' as const) : ('Không' as const),
      notes: i === 1 ? 'Lớp trưởng gương mẫu' : '',
    });
  }
  return students;
}

